#[test]
fn test_type_safe_column_creation_comprehensive() {
    // Test integer primary key column
    let id_column = TypeSafeColumnBuilder::new(UserIdColumn).primary_key();
    assert_eq!(id_column.column_name(), "id");
    assert_eq!(id_column.sql_type(), "INTEGER");
    assert!(id_column.constraints().iter().any(|c| matches!(c, ColumnConstraint::PrimaryKey)));
    assert!(id_column.constraints().iter().any(|c| matches!(c, ColumnConstraint::NotNull)));

    // Test string column with unique constraint
    let email_column = TypeSafeColumnBuilder::new(UserEmailColumn).not_null().unique();
    assert_eq!(email_column.column_name(), "email");
    assert_eq!(email_column.sql_type(), "TEXT");
    assert!(email_column.constraints().iter().any(|c| matches!(c, ColumnConstraint::NotNull)));
    assert!(email_column.constraints().iter().any(|c| matches!(c, ColumnConstraint::Unique)));

    // Test boolean column with default
    let active_column = TypeSafeColumnBuilder::new(UserIsActiveColumn).default("1");
    assert_eq!(active_column.column_name(), "is_active");
    assert_eq!(active_column.sql_type(), "INTEGER"); // bool stored as INTEGER
    let has_default = active_column.constraints().iter().any(|c| {
        if let ColumnConstraint::Default(val) = c {
            val == "1"
        } else {
            false
        }
    });
    assert!(has_default, "Expected default constraint with value '1'");

    // Test float column
    let score_column = TypeSafeColumnBuilder::new(UserScoreColumn);
    assert_eq!(score_column.column_name(), "score");
    assert_eq!(score_column.sql_type(), "REAL");

    // Test optional column
    let age_column = TypeSafeColumnBuilder::new(UserAgeColumn);
    assert_eq!(age_column.column_name(), "age");
    assert_eq!(age_column.sql_type(), "INTEGER");
}

